export type Strings = typeof en;
export type ErrorKey = keyof Strings["errors"];
export type StatusKey = keyof Strings["statuses"];

/** Error from a command: a message key, or `server:<text>` from the API. */
export function errorMessage(t: Strings, key: unknown): string {
  if (typeof key === "string" && key.startsWith("server:")) {
    return key.slice("server:".length);
  }
  return typeof key === "string" && key in t.errors ? t.errors[key as ErrorKey] : t.errors.failed;
}

